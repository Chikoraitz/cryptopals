void validate_aes_sub_bytes() {
  byte state[AES_STATE_COLUMN_SIZE][AES_STATE_ROW_SIZE];

  for(int test=0; test < N_TESTS; test++) {
    memcpy(state, fips197_start_of_round[test], AES_BLOCK_SIZE);
    
    aes_sub_bytes(FORWARD, state);
    for(int col=0; col < AES_STATE_COLUMN_SIZE; col++) {
      for(int row=0; row < AES_STATE_ROW_SIZE; row++) {
        assert_int_equal(state[col][row], fips197_after_sub_bytes[test][col][row]);
      }
    }

    aes_sub_bytes(INVERSE, state);
    for(int col=0; col < AES_STATE_COLUMN_SIZE; col++) {
      for(int row=0; row < AES_STATE_ROW_SIZE; row++) {
        assert_int_equal(state[col][row], fips197_start_of_round[test][col][row]);
      }
    }
  }
}


